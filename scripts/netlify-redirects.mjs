#!/usr/bin/env node
/**
 * Generate `client/dist/_redirects` for Netlify.
 *
 * Order matters — Netlify uses the first matching rule:
 *   1. /api/*     → <API_ORIGIN>/api/:splat      (proxy, keeps cookies same-origin)
 *   2. /uploads/* → <API_ORIGIN>/uploads/:splat  (logos, documents, avatars)
 *   3. /*         → /index.html                  (SPA deep links)
 *
 * Configure with the API_ORIGIN environment variable on Netlify.
 * When it is not set the file still contains the SPA fallback, so a build that
 * is served by the Express server keeps working.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dist = path.join(root, 'client', 'dist');

const rawOrigin = process.env.API_ORIGIN || process.env.VITE_API_ORIGIN || '';
const origin = rawOrigin.trim().replace(/\/+$/, '');

if (rawOrigin && !/^https?:\/\//i.test(origin)) {
  console.error(`[netlify] API_ORIGIN must start with http:// or https:// (received "${rawOrigin}")`);
  process.exit(1);
}

if (!fs.existsSync(dist)) {
  console.error('[netlify] client/dist is missing — run the client build first.');
  process.exit(1);
}

const lines = [
  '# Generated by scripts/netlify-redirects.mjs — do not edit by hand.',
  '# Netlify applies the first matching rule, so proxy rules must come first.',
];

if (origin) {
  lines.push(`/api/*      ${origin}/api/:splat        200`);
  lines.push(`/uploads/*  ${origin}/uploads/:splat    200`);
} else {
  lines.push('# API_ORIGIN was not set: no proxy rules generated (same-origin hosting assumed).');
}

lines.push('/*          /index.html                 200', '');

const target = path.join(dist, '_redirects');
fs.writeFileSync(target, lines.join('\n'), 'utf8');

console.log(`[netlify] wrote ${path.relative(root, target)}`);
console.log(origin ? `[netlify] API proxy → ${origin}` : '[netlify] no API proxy configured (SPA fallback only)');
if (process.env.VITE_API_BASE) {
  console.log(`[netlify] VITE_API_BASE is set (${process.env.VITE_API_BASE}); the browser will call the API directly.`);
}
